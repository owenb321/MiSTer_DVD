//============================================================================
//  imdct_512_tb.sv — standalone unit test for imdct_512 (M8).
//
//  Loads imdct_coeff.mem (2 ch × 256 Q1.23 coeffs) into a TB-resident
//  coefficient store, runs the DUT, then compares every Q8.23 output sample to
//  imdct_golden.mem (liba52's a52_imdct_512 output requantized to Q8.23).  This
//  is the first stage past mantissa_dequant that does its own DSP, and like it
//  is fixed-point, so the check is **bounded error** (not bit-exact): the TB
//  reports the max abs error in Q8.23 LSB and fails only past TOL_LSB.
//  Generated by gen_imdct_vec.c; driven by bench/ac3/run_imdct.sh.
//============================================================================
`timescale 1ns/1ps

module imdct_512_tb;
    logic clk = 0;
    always #5 clk = ~clk;
    logic rst;

    // coefficient store (stands in for mantissa_dequant.coeff_mem)
    logic signed [23:0] coeff_src [0:511];
    logic signed [31:0] golden    [0:511];

    // M14: coeff/pcm addrs are 11-bit ({ch[2:0], idx[7:0]}); this 2-channel
    // torture vector uses ch0/ch1 only, so addresses stay < 512.
    logic [10:0] coeff_rd_addr;
    logic signed [23:0] coeff_rd_data;
    // M13: coeff_mem is now a synchronous M10K read in the integrated design
    // (mantissa_dequant), so model the 1-cycle read latency here too — imdct_512
    // S_PRE was shifted to match.  A combinational source would break the new
    // phasing.
    always_ff @(posedge clk) coeff_rd_data <= coeff_src[coeff_rd_addr[8:0]];

    logic [10:0] pcm_rd_addr;
    logic signed [31:0] pcm_rd_data;
    logic        start, done;

    // nfchans=2 → S_DMX downmix is bypassed (L/R passthrough), matching the
    // 2-channel liba52 golden; cmixlev/surmixlev are then don't-care.
    imdct_512 dut (
        .clk(clk), .rst(rst),
        .start(start),
        // dynrng: UNITY is 8'h00 under the correct (M17) two's-complement
        // exponent decode; the golden applies no DRC.  (This TB used to drive
        // 8'h80 — unity only under the PRE-M17 buggy unsigned decode — and had
        // been silently failing 16x-scaled ever since the M17 fix.)
        .nfchans(3'd2), .blksw(5'd0), .dynrng(8'h00), .cmixlev(2'd0), .surmixlev(2'd0),
        .coeff_rd_addr(coeff_rd_addr), .coeff_rd_data(coeff_rd_data),
        .pcm_rd_addr(pcm_rd_addr), .pcm_rd_data(pcm_rd_data),
        .done(done)
    );

    // tolerance in Q8.23 LSB (1 LSB = 2^-23 ~ 1.2e-7).  Measured max on this
    // full-scale torture vector (every one of 256 bins at random Q1.23, peak
    // |sample| ~ 17) is ~1666 LSB ~ 2.0e-4 abs ~ 1.2e-5 relative ~ 0.4 LSB @
    // s16 — an order under the +/-2-LSB-@-s16 budget.  3000 leaves head-room;
    // real (sparse, low-level) content errs far less.
    localparam integer TOL_LSB = 3000;

    integer k, errs, maxerr, e, timeout;
    initial begin
        $readmemh("imdct_coeff.mem",  coeff_src);
        $readmemh("imdct_golden.mem", golden);

        rst = 1; start = 0; pcm_rd_addr = 0;
        repeat (4) @(posedge clk);
        rst = 0;
        @(posedge clk);
        start = 1; @(posedge clk); start = 0;

        // wait for completion (huge headroom; bound it so a hang fails loudly)
        timeout = 0;
        while (!done && timeout < 200000) begin @(posedge clk); timeout = timeout + 1; end
        if (!done) begin $display("FAIL: imdct_512 never asserted done"); $fatal; end

        errs = 0; maxerr = 0;
        for (k = 0; k < 512; k = k + 1) begin
            pcm_rd_addr = k[10:0];
            #1;
            e = pcm_rd_data - golden[k];
            if (e < 0) e = -e;
            if (e > maxerr) maxerr = e;
            if (e > TOL_LSB) begin
                errs = errs + 1;
                if (errs <= 10)
                    $display("  mismatch [%0d] ch%0d idx%0d: dut=%0d golden=%0d (err=%0d LSB)",
                             k, k[8], k[7:0], pcm_rd_data, golden[k], e);
            end
        end

        $display("imdct_512: max abs error = %0d Q8.23 LSB (~%e), tol = %0d",
                 maxerr, maxerr / 8388608.0, TOL_LSB);
        if (errs == 0) $display("PASS: imdct_512 within tolerance (512 samples)");
        else begin
            $display("FAIL: %0d sample(s) exceeded tolerance", errs);
            $fatal(1);   // nonzero exit — a plain $finish let run scripts read FAIL as pass
        end
        $finish;
    end
endmodule

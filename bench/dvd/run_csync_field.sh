#!/usr/bin/env bash
#
# run_csync_field.sh — composite-sync field symmetry of the interlaced main raster
# (bench/dvd/csync_field_tb.sv; docs/single_raster_analog.md).
#
# The framework `csync` module lives inside sys/sys_top.v, which cannot be compiled
# standalone (VHDL neighbours, includes). Extract it at run time into a generated
# file so the bench always tests the REAL module, never a copy that can drift.
# One mechanical edit on the way: iverilog rejects the module's use-before-declare
# (`assign csync = ...` above `reg csync_hs, csync_vs;`), so the reg line is hoisted
# above the assign. Logic untouched.
set -e
cd "$(dirname "$0")/../.."

gen=bench/dvd/csync_ref_gen.v
{
  echo "// GENERATED by bench/dvd/run_csync_field.sh from sys/sys_top.v — do not edit"
  awk '/^module csync$/,/^endmodule/' sys/sys_top.v \
    | sed 's/^module csync$/module csync_ref/' \
    | awk '
        /^reg csync_hs, csync_vs;/ { next }                       # drop from original spot
        /^assign csync = / { print "reg csync_hs, csync_vs;"; }  # hoist above the assign
        { print }'
} > "$gen"
grep -q "reg csync_hs, csync_vs;" "$gen" || { echo "csync extraction failed"; exit 1; }

iverilog -g2012 -I rtl/mpeg2 -o bench/dvd/csync_field_sim \
  rtl/mpeg2/syncgen.v "$gen" bench/dvd/csync_field_tb.sv
vvp bench/dvd/csync_field_sim

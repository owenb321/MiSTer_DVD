#!/usr/bin/env python3
"""nav_isa.py -- the navigation sequencer: its instruction set, the assembler,
the ROM image, and the instruction-level emulator (docs/nav_engine.md).

The DVD VM (dvd/dvd_vm.sv) is a microcoded sequencer (dvd/nav/nav_seq.sv) inside a
thin hardwired wrapper. The program, dvd/nav/vm.uasm, is the DVD virtual machine:
command fetch and decode, compare/set/link/jump, the fallback chain, RSM, the
counter-mode tick. The wrapper keeps everything real-time: event latches and their
priority, the wait timer, the output pulses and fields, the SPRM8/SPRM3 shadows,
pre_done, the LFSR. tools/nav_shell.py models that wrapper; this file is the
sequencer. The RTL must match the emulator instruction by instruction.

The method is the audio engine's (tools/dts_isa.py, docs/dts_decoder.md sec 10),
but this is its own small machine: no bit reader, no Huffman walker, no vector ops.
It does not share the audio engine's silicon (docs/logic_reclaim.md sec 10b).

Instruction word, 40 bits (the DTS layout, for familiarity):
    op[39:34] rd[33:30] rs[29:26] rt[25:22] imm[21:6] aux[5:0]
Registers r0..r15 are 16 bits, unsigned; r0 reads 0.

    alu   rd, rs, rt        rd = rs FN rt                  (FN in aux)
    alui  rd, rs, imm       rd = rs FN imm16
    dcmp  rd, rs, rt, rk    rd = the DVD compare (rk & 7) of rs and rt  (rk in aux)
                            0 true, 1 |(a&b), 2 ==, 3 !=, 4 >=, 5 >, 6 <=, 7 <
    ld    rd, imm[rs]       rd = RAM[(rs + imm) & 0xFF]     the data RAM, 256 x 16
    st    rd, imm[rs]       RAM[(rs + imm) & 0xFF] = rd
    ldc   rd, imm[rs]       rd = CMD[(rs + imm) & 0x7FF]    command words, big-endian
    ldp   rd, imm[rs]       rd = PMAP[(rs + imm) & 0x7F]    the program map (bytes)
    in    rd, PORT[rs]      rd = the wrapper's input (aux + rs) & 63
    out   PORT, rs          the wrapper's output aux = rs
    outi  PORT, imm         the wrapper's output aux = imm16
    b<c>  rs, rt, label     branch if rs <c> rt, c in eq ne ltu geu (unsigned)
    b<c>i rs, k, label      ... against an unsigned 10-bit constant k
    bbs / bbc rs, n, label  branch if bit n of rs is set / clear
    jmp / call label, ret   (call stack depth 4)
    jr    rs, label         pc = label + rs (a jump table)
    wev   label, mode       wait for an event, then pc = label + its index
                            (mode 0 = the idle priority set, 1 = the wait set)

Timing: ld, ldc and ldp take 2 cycles, everything else 1; wev waits.

The trace the RTL is scored against (Machine.trace): one tuple (kind, pc, addr,
value) per event, in program order --
    kind 0  a register write    addr = the register, value 16 bits
    kind 1  a store             addr = the RAM address, value 16 bits
    kind 2  an output           addr = the port, value 16 bits
    kind 3  an event dispatch   addr = the mode, value = the index

Usage:
    tools/nav_isa.py --asm [--check]      # assemble dvd/nav/vm.uasm -> dvd/nav/*.mem, .svh
    tools/nav_isa.py --list               # the program with addresses
    tools/nav_isa.py --mutate ARM --mem-out x.mem   # a RED arm's ROM image
    tools/nav_isa.py --mutant ARM DIR     # ... as a runnable dvd_vm.sv (prints its path)
"""

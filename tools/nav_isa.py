GEN_BEGIN = '// ==== BEGIN GENERATED by tools/nav_isa.py --asm (never edit) ===='
GEN_END = '// ==== END GENERATED ===='

OPS = ['nop', 'alu', 'alui', 'dcmp', 'ld', 'st', 'ldc', 'ldp', 'in', 'out', 'outi',
       'br', 'bri', 'bb', 'jmp', 'call', 'ret', 'jr', 'wev']
OP = {n: i for i, n in enumerate(OPS)}
FNS = ['add', 'sub', 'and', 'or', 'xor', 'shl', 'shr', 'sadd', 'ssub',
       'seq', 'sne', 'sltu', 'sgeu']
FN = {n: i for i, n in enumerate(FNS)}
CONDS = ['eq', 'ne', 'ltu', 'geu']
STACK_DEPTH = 4
UC_DEPTH = 1024                  # 4 M10K at 40 bits (256 x 40 each)
RAM_WORDS = 256
CMD_WORDS = 2048                 # 4096 bytes = 512 commands, the reader's table
PMAP_BYTES = 128

# ------------------------------------------------------------------ the wrapper's ports
# Inputs (in): reader read-backs, cfg, and the wrapper's own state.
IN_PORTS = [
    'CUR_VTS', 'CUR_PGCN', 'CUR_CELL', 'CELL_COUNT', 'NEXT_PGCN', 'PREV_PGCN', 'GOUP_PGCN',
    'NR_PRE', 'NR_POST', 'NR_CELL', 'NR_PGMS', 'AUTO_VTS', 'BEST_MENU_VTS', 'RES_TTN',
    'MENU_ACTIVE', 'CC_NR', 'CHEDGE_DIR', 'LFSR', 'VM_DOM', 'VM_VTS', 'MENU_SEEN',
    'LM_V', 'LM_DOM', 'LM_VTS', 'LM_PGCN', 'JPGCN', 'EVENTS', 'ZERO27',
    'BTN0', 'BTN1', 'BTN2', 'BTN3']
IN = {n: i for i, n in enumerate(IN_PORTS)}
IN['SPRMW'] = 32                 # 32..63: the live-SPRM window (0 for RAM-resident SPRMs)
# Outputs (out / outi). J_DE = {entry[3:0], 2'b0, dom[1:0]} (entry << 4 | dom).
OUT_PORTS = [
    'J_DE', 'J_VTS', 'J_PGCN', 'RSV3', 'J_TTN', 'J_PGN', 'J_PTT', 'J_CELL',
    'SEEK_CELL', 'PULSE', 'BTNF_VAL', 'LF_PGCN', 'SPRM1', 'SPRM2', 'SPRM3', 'SPRM8',
    'VM_DOM', 'VM_VTS', 'FLAGS', 'EVCLR', 'EVSET']
OUT = {n: i for i, n in enumerate(OUT_PORTS)}
# PULSE bits
PULSE_BITS = ['JUMP', 'SEEK', 'REPLAY', 'ADV', 'BTNF', 'LINKFAIL', 'LFSTEP', 'WARM', 'TICKDONE']
PB = {n: 1 << i for i, n in enumerate(PULSE_BITS)}
# FLAGS bits: blk[1:0], nat_src, usr_edge, walk (the tick walk counts as V_IDLE)
FLAG_BITS = {'BLK': 0, 'NAT': 2, 'USR': 3, 'WALK': 4}     # bit positions; blk is 2 bits
# Event latches (EVENTS / EVCLR / EVSET bit order); WEV idle index = bit + 2
EVENTS = ['BOOT', 'ERROR', 'LOADED', 'BTN', 'CELLCMD', 'PGCEND', 'CHEDGE',
          'MENU', 'TITLE', 'CMENU', 'RETURN']
EV = {n: 1 << i for i, n in enumerate(EVENTS)}
# WEV indices
WEV_IDLE = ['TICK', 'DISABLED'] + EVENTS
WEV_WAIT = ['LOADED', 'ERROR', 'TIMEOUT']

# ------------------------------------------------------------------ the data RAM map
# One single-port M10K, touched only by ld/st. Everything the old FSM kept in flops
# that only the VM reads lives here.
RAM_MAP = {
    'GPRM': 0x00,        # 0x00..0x0F the 16 GPRMs
    'GMODE': 0x10,       # counter-mode bits, one per GPRM
    'FB': 0x11,          # the fallback-chain state (FB_*)
    'CVM': 0x12,         # came_via_menukey
    'SKIP_PRE': 0x13,
    'TT_RESOLVE': 0x14,
    'CHAIN': 0x15,       # VM-issued jumps this activation
    'RSM_VTS': 0x18, 'RSM_PGCN': 0x19, 'RSM_CELL': 0x1A,
    'RSM_R4': 0x1B, 'RSM_R5': 0x1C, 'RSM_R6': 0x1D, 'RSM_R7': 0x1E, 'RSM_R8': 0x1F,
    'DE_SEEN': 0x20, 'DE_VTS': 0x21, 'DE_PGCN': 0x22,
    'T0': 0x28,          # 0x28..0x2F handler scratch
    'SPRMI': 0x40,       # 0x40..0x5F the SPRM image: 4..7, 9, 10, 13 live here
}
FB_CODES = {'FB_NONE': 0, 'FB_FP': 1, 'FB_VTSM': 2, 'FB_VTSM2': 3, 'FB_VMGM': 4,
            'FB_TITLE': 5, 'FB_GAVEUP': 6, 'FB_BOOTM': 7}
DOM_CODES = {'DOM_FP': 0, 'DOM_VMGM': 1, 'DOM_VTSM': 2, 'DOM_TT': 3}
BLK_CODES = {'BLK_PRE': 0, 'BLK_POST': 1, 'BLK_CELL': 2, 'BLK_BTN': 3}


def encode(op, rd=0, rs=0, rt=0, imm=0, aux=0):
    return (OP[op] << 34) | ((rd & 15) << 30) | ((rs & 15) << 26) | ((rt & 15) << 22) | \
        ((imm & 0xFFFF) << 6) | (aux & 63)


def decode(w):
    return (OPS[(w >> 34) & 63], (w >> 30) & 15, (w >> 26) & 15, (w >> 22) & 15,
            (w >> 6) & 0xFFFF, w & 63)


def base_equ():
    """The names every program may use: ports, pulse/flag/event bits, the RAM map."""
    equ = {}
    equ.update({'P_' + k: v for k, v in IN.items()})
    equ.update({'O_' + k: v for k, v in OUT.items()})
    equ.update({'PB_' + k: v for k, v in PB.items()})
    equ.update({'F_' + k: 1 << v for k, v in FLAG_BITS.items() if k != 'BLK'})
    equ.update({'FBIT_' + k: v for k, v in FLAG_BITS.items() if k != 'BLK'})
    equ.update({'EV_' + k: v for k, v in EV.items()})
    equ['EV_ALL'] = (1 << len(EVENTS)) - 1
    equ.update({'M_' + k: v for k, v in RAM_MAP.items()})
    equ.update(FB_CODES)
    equ.update(DOM_CODES)
    equ.update(BLK_CODES)
    return equ


# ------------------------------------------------------------------ assembler
class AsmError(Exception):
    pass


def _reg(tok, aliases):
    tok = aliases.get(tok.strip().lower(), tok.strip().lower())
    m = re.fullmatch(r'r(\d+)', tok)
    if not m or int(m.group(1)) > 15:
        raise AsmError(f'not a register: {tok!r}')
    return int(m.group(1))


def _is_reg(tok, aliases):
    tok = aliases.get(tok.strip().lower(), tok.strip().lower())
    return re.fullmatch(r'r\d+', tok) is not None


def assemble(text, mutate=None):
    """-> (words, labels, line numbers). `mutate`: a name; a line carrying
    `;MUT <name>: <instruction>` assembles that instruction instead (the RED arms
    live beside the code they break, as in tools/dts_isa.py)."""
    equ = base_equ()
    aliases, labels, stmts = {}, {}, []
    mutated = False
    for ln, raw in enumerate(text.splitlines(), 1):
        mm = re.search(r';\s*MUT\s+(\w+)\s*:\s*(.*)$', raw)
        line = raw
        if mm and mutate == mm.group(1):
            line = re.sub(r'^(\s*(?:[A-Za-z_][\w.]*:\s*)*).*$', lambda m_: m_.group(1) + mm.group(2), raw)
            mutated = True
        line = re.sub(r';.*', '', line).strip()
        if not line:
            continue
        while True:
            m = re.match(r'([A-Za-z_][\w.]*):\s*(.*)$', line)
            if not m:
                break
            if m.group(1) in labels:
                raise AsmError(f'line {ln}: label {m.group(1)} twice')
            labels[m.group(1)] = len(stmts)
            line = m.group(2).strip()
        if not line:
            continue
        if line.startswith('.equ'):
            _, name, val = line.split(None, 2)
            equ[name] = int(eval(val, {'__builtins__': {}}, dict(equ)))
            continue
        if line.startswith('.reg'):
            _, name, reg = line.split(None, 2)
            aliases[name.lower()] = reg.strip().lower()
            continue
        stmts.append((ln, line, dict(aliases)))
    if mutate and not mutated:
        raise AsmError(f'no MUT {mutate} in the source')
    if len(stmts) > UC_DEPTH:
        raise AsmError(f'{len(stmts)} words exceed the {UC_DEPTH}-word ROM')

    def ev(expr, ln):
        env = dict(equ)
        env.update(labels)
        try:
            return int(eval(expr, {'__builtins__': {}}, env))
        except Exception as e:
            raise AsmError(f'line {ln}: cannot evaluate {expr!r} ({e})')

    words = []
    for ln, line, al in stmts:
        m = re.match(r'(\w+)\s*(.*)$', line)
        mn, rest = m.group(1).lower(), m.group(2)
        args = [a.strip() for a in re.split(r',(?![^\[]*\])', rest)] if rest else []

        def reg(i):
            return _reg(args[i], al)

        def memref(s):
            m2 = re.fullmatch(r'(.*?)\s*\[([^\]]*)\]', s)
            if not m2:
                return ev(s, ln), 0
            imm = ev(m2.group(1), ln) if m2.group(1).strip() else 0
            return imm, (_reg(m2.group(2), al) if m2.group(2).strip() else 0)

        def imm16(v):
            if not -0x8000 <= v <= 0xFFFF:
                raise AsmError(f'line {ln}: constant {v} does not fit 16 bits')
            return v & 0xFFFF

        try:
            if mn in FN:
                if _is_reg(args[2], al):
                    words.append(encode('alu', reg(0), reg(1), reg(2), 0, FN[mn]))
                else:
                    words.append(encode('alui', reg(0), reg(1), 0, imm16(ev(args[2], ln)), FN[mn]))
            elif mn.endswith('i') and mn[:-1] in FN:
                words.append(encode('alui', reg(0), reg(1), 0, imm16(ev(args[2], ln)), FN[mn[:-1]]))
            elif mn == 'li':
                words.append(encode('alui', reg(0), 0, 0, imm16(ev(args[1], ln)), FN['add']))
            elif mn == 'mov':
                words.append(encode('alu', reg(0), reg(1), 0, 0, FN['add']))
            elif mn == 'dcmp':
                words.append(encode('dcmp', reg(0), reg(1), reg(2), 0, reg(3)))
            elif mn in ('ld', 'st', 'ldc', 'ldp'):
                imm, ra = memref(args[1])
                words.append(encode(mn, reg(0), ra, 0, imm16(imm)))
            elif mn == 'in':
                port, ra = memref(args[1])
                if not 0 <= port <= 63:
                    raise AsmError(f'line {ln}: input port {port}')
                words.append(encode('in', reg(0), ra, 0, 0, port))
            elif mn == 'out':
                port = ev(args[0], ln)
                words.append(encode('out', 0, reg(1), 0, 0, port))
            elif mn == 'outi':
                port = ev(args[0], ln)
                words.append(encode('outi', 0, 0, 0, imm16(ev(args[1], ln)), port))
            elif mn[:1] == 'b' and mn[1:] in CONDS:
                words.append(encode('br', CONDS.index(mn[1:]), reg(0), reg(1), ev(args[2], ln)))
            elif mn[:1] == 'b' and mn[1:-1] in CONDS and mn[-1] == 'i':
                c = ev(args[1], ln)
                if not 0 <= c <= 1023:
                    raise AsmError(f'line {ln}: branch constant {c} outside 0..1023')
                words.append(encode('bri', CONDS.index(mn[1:-1]), reg(0), c >> 6,
                                    ev(args[2], ln), c & 63))
            elif mn in ('bbs', 'bbc'):
                n = ev(args[1], ln)
                if not 0 <= n <= 15:
                    raise AsmError(f'line {ln}: bit {n}')
                words.append(encode('bb', 1 if mn == 'bbs' else 0, reg(0), n, ev(args[2], ln)))
            elif mn in ('jmp', 'call'):
                words.append(encode(mn, 0, 0, 0, ev(args[0], ln)))
            elif mn == 'jr':
                words.append(encode('jr', 0, reg(0), 0, ev(args[1], ln)))
            elif mn == 'wev':
                words.append(encode('wev', 0, 0, 0, ev(args[0], ln), ev(args[1], ln)))
            elif mn in ('ret', 'nop'):
                words.append(encode(mn))
            else:
                raise AsmError(f'line {ln}: unknown instruction {mn!r}')
        except (IndexError, KeyError) as e:
            raise AsmError(f'line {ln}: bad operands in {line!r} ({e})')
    for w, (ln, line, _) in zip(words, stmts):
        op, rd, rs, rt, imm, aux = decode(w)
        if op in ('br', 'bri', 'bb', 'jmp', 'call', 'jr', 'wev') and imm >= len(words):
            raise AsmError(f'line {ln}: target {imm} is past the program')
    return words, labels, [ln for ln, _, _ in stmts]


def load_program(mutate=None):
    return assemble(open(UASM).read(), mutate)


# ------------------------------------------------------------------ emulator
class SeqError(Exception):
    pass


def alu(fn, a, b):
    a &= 0xFFFF
    b &= 0xFFFF
    if fn == 0:
        return (a + b) & 0xFFFF
    if fn == 1:
        return (a - b) & 0xFFFF
    if fn == 2:
        return a & b
    if fn == 3:
        return a | b
    if fn == 4:
        return a ^ b
    if fn == 5:
        return (a << (b & 15)) & 0xFFFF
    if fn == 6:
        return a >> (b & 15)
    if fn == 7:
        return min(a + b, 0xFFFF)
    if fn == 8:
        return max(a - b, 0)
    if fn == 9:
        return int(a == b)
    if fn == 10:
        return int(a != b)
    if fn == 11:
        return int(a < b)
    if fn == 12:
        return int(a >= b)
    raise SeqError(f'alu function {fn}')


def dvd_compare(op, a, b):
    """libdvdnav decoder.c eval_compare; op 0 = no compare = true."""
    op &= 7
    return int([True, bool(a & b), a == b, a != b, a >= b, a > b, a <= b, a < b][op])


CYC = {'instr': 1, 'ld': 2}


class Machine:
    """The sequencer. `io` is the wrapper (tools/nav_shell.py Shell): it answers
    in/out, ldc/ldp and wev. run() executes until the program waits at a wev with
    nothing to dispatch."""

    def __init__(self, words, io):
        self.prog = words
        self.io = io
        self.reset()

    def reset(self):
        self.reg = [0] * 16
        self.pc = 0
        self.stack = []
        self.ram = [0] * RAM_WORDS
        self.trace = []
        self.cycles = 0
        self.waiting = None          # the wev mode we are parked at, or None

    def _wr(self, rd, v):
        if rd:
            self.reg[rd] = v & 0xFFFF
            self.trace.append((0, self.pc, rd, v & 0xFFFF))

    def step(self):
        """Execute one instruction. -> False if parked at a wev with nothing to do."""
        w = self.prog[self.pc]
        op, rd, rs, rt, imm, aux = decode(w)
        R = self.reg
        npc = self.pc + 1
        cyc = CYC['instr']
        if op == 'nop':
            pass
        elif op == 'alu':
            self._wr(rd, alu(aux & 15, R[rs], R[rt]))
        elif op == 'alui':
            self._wr(rd, alu(aux & 15, R[rs], imm))
        elif op == 'dcmp':
            self._wr(rd, dvd_compare(R[aux & 15], R[rs], R[rt]))
        elif op == 'ld':
            self._wr(rd, self.ram[(R[rs] + imm) & 0xFF])
            cyc = CYC['ld']
        elif op == 'st':
            a = (R[rs] + imm) & 0xFF
            self.ram[a] = R[rd]
            self.trace.append((1, self.pc, a, R[rd]))
        elif op == 'ldc':
            self._wr(rd, self.io.ldc((R[rs] + imm) & (CMD_WORDS - 1)))
            cyc = CYC['ld']
        elif op == 'ldp':
            self._wr(rd, self.io.ldp((R[rs] + imm) & (PMAP_BYTES - 1)))
            cyc = CYC['ld']
        elif op == 'in':
            self._wr(rd, self.io.inp((aux + R[rs]) & 63))
        elif op in ('out', 'outi'):
            v = R[rs] if op == 'out' else imm
            self.trace.append((2, self.pc, aux, v))
            self.io.out(aux, v)
        elif op in ('br', 'bri', 'bb'):
            a = R[rs]
            if op == 'bb':
                take = bool((a >> rt) & 1) == bool(rd & 1)
            else:
                b = R[rt] if op == 'br' else ((rt << 6) | aux)
                take = [a == b, a != b, a < b, a >= b][rd & 3]
            if take:
                npc = imm
        elif op == 'jmp':
            npc = imm
        elif op == 'call':
            if len(self.stack) >= STACK_DEPTH:
                raise SeqError(f'call stack overflow at pc {self.pc}')
            self.stack.append(self.pc + 1)
            npc = imm
        elif op == 'ret':
            if not self.stack:
                raise SeqError(f'ret with an empty stack at pc {self.pc}')
            npc = self.stack.pop()
        elif op == 'jr':
            npc = (imm + R[rs]) & (UC_DEPTH - 1)
        elif op == 'wev':
            idx = self.io.wev(aux)
            if idx is None:
                self.waiting = aux
                return False
            self.waiting = None
            self.trace.append((3, self.pc, aux, idx))
            npc = imm + idx
        else:
            raise SeqError(f'opcode {op} at pc {self.pc}')
        if npc >= len(self.prog):
            raise SeqError(f'pc {npc} past the program (from {self.pc})')
        self.cycles += cyc
        self.pc = npc
        return True

    def run(self, limit=2_000_000):
        """Run until parked. -> instructions executed."""
        n = 0
        while self.step():
            n += 1
            if n > limit:
                raise SeqError(f'no wev after {limit} instructions (pc {self.pc})')
        return n


# ------------------------------------------------------------------ ROM image
def ucode_svh(words, labels):
    lines = ['// dvd/nav/nav_ucode.svh -- GENERATED by tools/nav_isa.py --asm; never edit.',
             '// The navigation sequencer\'s program size, opcodes, ports, and the data RAM',
             '// map (docs/nav_engine.md). Benches read the RAM through these addresses.',
             f'localparam integer UC_WORDS = {len(words)};',
             f'localparam integer UC_DEPTH = {UC_DEPTH};']
    for n, i in OP.items():
        lines.append(f"localparam [5:0] UOP_{n.upper()} = 6'd{i};")
    for n, i in FN.items():
        lines.append(f"localparam [3:0] UFN_{n.upper()} = 4'd{i};")
    for n, i in IN.items():
        lines.append(f"localparam [5:0] UIN_{n} = 6'd{i};")
    for n, i in OUT.items():
        lines.append(f"localparam [5:0] UOUT_{n} = 6'd{i};")
    for i, n in enumerate(PULSE_BITS):
        lines.append(f'localparam integer UPB_{n} = {i};')
    for n, b in FLAG_BITS.items():
        lines.append(f'localparam integer UFL_{n} = {b};')
    for i, n in enumerate(EVENTS):
        lines.append(f'localparam integer UEV_{n} = {i};')
    lines.append(f'localparam integer UEV_N = {len(EVENTS)};')
    for n, a in RAM_MAP.items():
        lines.append(f"localparam [7:0] UM_{n} = 8'h{a:02x};")
    for n, v in FB_CODES.items():
        lines.append(f"localparam [2:0] U{n} = 3'd{v};")
    return lines


